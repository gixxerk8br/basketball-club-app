-- 1. 列を追加(すでに存在すればスキップ)
alter table schedule_days add column if not exists event_name text;

-- 2. 既存データの移行: これまで「メモ」に入れていた大会名・行事名を「予定」へ移す。
--    すでにevent_nameが入っている行(このSQLを再実行した場合など)や、
--    メモが空の行は対象外(安全のため、上書きしない)。
update schedule_days
set event_name = memo, memo = null
where (event_name is null or event_name = '') and memo is not null and memo <> '';

