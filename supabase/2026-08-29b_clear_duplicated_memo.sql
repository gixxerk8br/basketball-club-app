--
-- 「メモ」の内容が「予定」と完全に一致する行だけ、メモを空にします。
-- 大会名以外の内容(持ち物・注意事項など)がメモに入っている行は、
-- 予定の内容と一致しないため、このSQLでは一切変更されません。
