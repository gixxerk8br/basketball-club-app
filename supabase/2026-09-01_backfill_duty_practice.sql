-- ============================================================
-- WILD CATSアプリ: 当番だけ入っていて種類が未設定の日程を「練習」に一括更新
-- 作成日: 2026-09-01
--
-- 過去のCSV一括登録等で、当番(duty)は入っているが種類(day_type)が
-- 未設定のまま残っている日程がある。「当番が入っていれば練習」という
-- ルールをアプリ側で自動選択するようにしたのに合わせて、既存データも
-- 同じ内容に統一する。
--
-- このSQLは Supabase の「SQL Editor」に貼り付けて実行してください。
-- 対象は「当番が入っていて、種類が未設定」の行のみ。既に何か種類が
-- 設定されている行(公式戦・カップ戦など)には一切影響しません。
-- 何度実行しても安全です(2回目以降は対象行が無いので何も起きません)。
-- ============================================================

update schedule_days
set day_type = '練習'
where duty is not null and duty <> ''
  and (day_type is null or day_type = '');

